function SolarSystem({ skills, color, Icon, title }: { skills: string[]; color: string; Icon: React.ElementType; title: string }) {
  const mid = Math.ceil(skills.length / 2)
  const inner = skills.slice(0, mid)
  const outer = skills.slice(mid)

  return (
    <div className="relative w-full h-60">
      {inner.length > 0 && <OrbitRing radius={55} />}
      {outer.length > 0 && <OrbitRing radius={90} />}
      <Sun color={color} Icon={Icon} title={title} />
      {inner.map((skill, i) => (
        <SkillPlanet
          key={skill}
          skill={skill}
          orbitRadius={55}
          orbitDuration={20 + i * 5}
          startAngle={(i / inner.length) * 2 * Math.PI}
        />
      ))}
      {outer.map((skill, i) => (
        <SkillPlanet
          key={skill}
          skill={skill}
          orbitRadius={90}
          orbitDuration={32 + i * 6}
          startAngle={(i / outer.length) * 2 * Math.PI + Math.PI / 4}
        />
      ))}
    </div>
  )
}

